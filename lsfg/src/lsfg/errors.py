"""The closed list of error classes (implementation.md §15.4).

Every StepResult.error and every trace failure uses exactly one of these names.
"""
from __future__ import annotations


class LsfgError(Exception):
    """Base class. `detail` carries observed values for traces and replans."""

    def __init__(self, message: str = "", **detail):
        super().__init__(message)
        self.message = message
        self.detail = detail

    @property
    def kind(self) -> str:
        return type(self).__name__


class PermissionMissing(LsfgError): ...
class AppNotFound(LsfgError): ...
class AppNotResponding(LsfgError): ...
class WindowNotFound(LsfgError): ...
class TreeUntrusted(LsfgError): ...
class TargetNotFound(LsfgError): ...
class TargetAmbiguous(LsfgError): ...
class TargetStale(LsfgError): ...
class FocusLost(LsfgError): ...
class ActionFailed(LsfgError): ...
class CheckFailed(LsfgError): ...
class Unverifiable(LsfgError): ...
class SafetyBlocked(LsfgError): ...
class BudgetExceeded(LsfgError): ...
class PlanInvalid(LsfgError): ...
class ModelUnavailable(LsfgError): ...
class ModelInvalidOutput(LsfgError): ...
class UserAborted(LsfgError): ...
class Cancelled(LsfgError): ...
class ScreenLocked(LsfgError): ...


ERROR_KINDS = tuple(cls.__name__ for cls in LsfgError.__subclasses__())
